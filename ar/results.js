export function relationship(score,group){const key=describeScore(score).key,[label,title,description]=C.bands[key];return{key,label,title,description,person:SHARING[group],context:C.context[group]};}
export function topic(key,bucket,group){const reading=relationship(bucket.score,group),copy=C.topics[key],band=reading.key==='middle'?'middle':bucket.score<0?'private':'open';return{...reading,scope:copy.scope,prompt:copy.prompt,detail:copy.detail,description:reading.key==='unscored'?C.unscored:copy[band].replaceAll('{person}',reading.person)};}
export function pattern(result,metadata){
 const entries=Object.entries(result.categories).filter(([,b])=>Number.isFinite(b.score));let title=C.minor,description;
 if(!entries.length)description=C.none;
 else if(entries.length===1)description=C.onlyA+metadata[entries[0][0]].label+C.onlyB;
 else{const sorted=[...entries].sort((a,b)=>b[1].score-a[1].score),high=sorted[0],low=sorted.at(-1),distinct=high[1].score-low[1].score>=40;title=distinct?C.distinctTitle:C.similarTitle;description=distinct?C.distinctA+metadata[high[0]].label+C.distinctB+metadata[low[0]].label+C.distinctC:C.similar;}
 return{title,description,note:result.answered<result.total?C.partial:C.whole};
}
export function coverage(result){return result.answered+C.coverageA+result.total+C.coverageB+Object.values(result.categories).filter(b=>b.score!==null).length+C.coverageC+Object.keys(result.categories).length+C.coverageD;}
export const shorten=text=>text.match(/^.*?[.!?؟۔](?:\s|$)/)?.[0]?.trim()||text;
export const plain=reading=>({description:shorten(reading.description),detail:reading.detail,context:reading.context});
export function scoringDetail(result,{pna,unknown,na}){return C.scoringA+result.answered+C.scoringB+result.total+C.scoringC+pna+C.scoringD+unknown+C.scoringE+na+C.scoringF+(result.total-result.answered-unknown-na)+'.';}
